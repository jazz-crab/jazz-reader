function renderTree() {
  const q = (el.treeFilter.value || '').trim().toLowerCase();
  el.paneFiles.innerHTML = '';
  if (!roots.length) {
    el.paneFiles.innerHTML = tr('tree.empty');
    return;
  }
  for (const r of roots) {
    const head = document.createElement('div');
    head.className = 'tree-root';
    const rm = document.createElement('button');
    rm.className = 'tree-remove';
    rm.innerHTML = ICONS.icon('x');
    rm.title = tr('tree.removeRoot');
    rm.onclick = () => {
      const i = roots.findIndex((x) => x.path === r.path);
      if (i >= 0) roots.splice(i, 1);
      renderTree();
    };
    const label = document.createElement('span');
    label.textContent = r.name + ' — ' + r.total + ' .md';
    label.title = r.path;
    head.append(label, rm);
    el.paneFiles.append(head);

    let shown = 0;
    for (const grp of r.tree) {
      if (grp.type === 'dir') {
        const d = document.createElement('div');
        d.className = 'tree-grp';
        const n = document.createElement('div');
        n.className = 'grp-name';
        n.innerHTML = ICONS.icon('folder', 'grp-ico') + '<span></span>';
        n.querySelector('span').textContent = grp.dir;
        d.append(n);
        el.paneFiles.append(d);
      } else {
        const box = document.createElement('div');
        for (const it of grp.items) {
          if (q && !it.name.toLowerCase().includes(q)) continue;
          shown++;
          const row = document.createElement('div');
          row.className = 'tree-item';
          row.title = it.full;
          // A file open in any tab is highlighted, the current tab even more strongly.
          const isCur = active() && samePath(active().path, it.full);
          const openInSome = isCur || [...tabs.values()].some((x) => samePath(x.path, it.full));
          if (openInSome) row.classList.add('is-open');
          if (isCur) row.classList.add('active');
          row.innerHTML = '<span class="fi">' + ICONS.icon('file') + '</span><span class="fn"></span><span class="sz"></span>';
          row.querySelector('.fn').textContent = it.name;
          row.querySelector('.sz').textContent = fmtSize(it.size);
          row.dataset.path = it.full;
          if (openInSome && !isCur) row.title = it.full + tr('status.openInOtherTab');
          row.onclick = () => openPath(it.full, { newTab: true });
          row.oncontextmenu = (e) => { e.preventDefault(); fileContextMenu(it.full, e.clientX, e.clientY); };
          box.append(row);
        }
        if (box.childNodes.length) el.paneFiles.append(box);
      }
    }
    if (!shown) {
      const none = document.createElement('div');
      none.className = 'tree-empty';
      none.textContent = q ? tr('tree.nothingFound') : tr('tree.noMdHere');
      el.paneFiles.append(none);
    }
  }
}

// ------------------------------------------------------------------ zoom

/* The zoom limits. Below 40% the text becomes unreadable, above 250% the bars
   stop fitting in the column and it starts jumping between lines. */
const ZOOM_MIN = 0.4;
const ZOOM_MAX = 2.5;

/* While something is being typed in the field, updateZoom does not touch it:
   otherwise every setZoom would wipe half of what was typed. */
let zoomEditing = false;

function updateZoom() {
  if (!zoomEditing) el.zoomVal.value = Math.round(zoom * 100) + '%';
  el.content.style.fontSize = (15 * zoom).toFixed(2) + 'px';
  el.editor.style.fontSize = (14 * zoom).toFixed(2) + 'px';
  el.zoomVal.classList.toggle('pending', zoomEditing);
}

function setZoom(z) {
  zoom = Math.min(ZOOM_MAX, Math.max(ZOOM_MIN, z));
  updateZoom();
}

/**
 * Apply the zoom typed into the field.
 *
 * We understand "85", "85%", "0.85", "1,85" and spaces around them. Silently
 * putting 100% on a typo is bad: the person thought they had set 130% and got
 * 100% without a word. So a failure is a line in the status bar and a return to
 * what it was.
 */
function applyZoomInput() {
  const raw = el.zoomVal.value.trim();
  const bare = raw.replace(/%/g, '').replace(',', '.').trim();
  let n = parseFloat(bare);
  if (raw === '' || !isFinite(n)) {
    status(tr('zoom.badValue') + raw, 'err');
    zoomEditing = false;
    updateZoom();
    return false;
  }
  // Without a "%" sign a number <= 1 is read as a fraction (0.85 -> 85%), above 1 —
  // as percentages (85 -> 85%). Otherwise "1" would mean 1% of the impossible.
  const z = raw.indexOf('%') >= 0 ? n / 100 : (n <= 1 ? n : n / 100);
  if (z < ZOOM_MIN || z > ZOOM_MAX) {
    status(tr('zoom.outOfRange') + Math.round(ZOOM_MIN * 100) + '–'
      + Math.round(ZOOM_MAX * 100) + '%: ' + raw, 'err');
    zoomEditing = false;
    updateZoom();
    return false;
  }
  zoom = z;
  zoomEditing = false;
  updateZoom();
  return true;
}

el.zoomVal.addEventListener('focus', () => {
  zoomEditing = true;
  el.zoomVal.select();
  el.zoomVal.classList.add('pending');
});
el.zoomVal.addEventListener('keydown', (e) => {
  if (e.key === 'Enter') {
    e.preventDefault();
    e.stopPropagation();
    applyZoomInput();
    el.zoomVal.blur();
    return;
  }
  // Escape — roll back to the real zoom, the field closes.
  // stopPropagation is required: otherwise the Escape that cancels the entry in
  // the field would reach the window handler and go on to the dialogs — where
  // it would close them and roll back the settings, that is, one keypress would
  // do three different things. The other keys are stopped below.
  if (e.key === 'Escape') {
    e.preventDefault();
    e.stopPropagation();
    zoomEditing = false;
    updateZoom();
    el.zoomVal.blur();
    return;
  }
  // The other keys must not fly into the window handler: a space there
  // would mean "scroll down", and "85 " would not apply.
  e.stopPropagation();
});
el.zoomVal.addEventListener('blur', () => {
  if (zoomEditing) applyZoomInput();
});
/* Ctrl+wheel over the field — a coarse adjustment, since the exact value is
   typed by hand. preventDefault is required: otherwise the page scrolls away. */
el.zoomVal.addEventListener('wheel', (e) => {
  e.preventDefault();
  setZoom(zoom + (e.deltaY < 0 ? 0.05 : -0.05));
}, { passive: false });

// ------------------------------------------------------- saving and the like

/**
 * Save a specific tab.
 *
 * A function of its own is needed for the dialogs: when closing a tab with
 * changes, the question may be about ANY tab, while save() worked only with the
 * active one and took the text from the editor. We take the text from the editor
 * only when the tab is active and in edit mode; for the others t.raw is already
 * current — it is updated on every keypress.
 */
async function saveTab(t) {
  if (!t || !t.path) return false;
  if (!t.dirty) return false;
  const text = (t === active() && t.mode === 'edit') ? el.editor.value : t.raw;
  try {
    await api.save(t.path, text);
    t.raw = text;
    t._diskRaw = text;
    t.dirty = false;
    t.mode = 'read';
    t.html = null;
    renderTabs();
    renderActive();
    toast(tr('status.saved') + t.name, 'ok');
    return true;
  } catch (e) {
    status(tr('status.saveFailed') + (e.message || e), 'err');
    return false;
  }
}

async function save() {
  const t = active();
  if (!t || !t.path) return;
  if (!t.dirty) { toast(tr('status.noChanges')); return; }
  // After saving we leave edit mode and go back to reading. save() used to
  // deliberately stay in edit mode (the thought being "Ctrl+S should not throw
  // you into reading"), but that meant that after saving you stayed in the editor
  // on an already clean file — and the green "Save" kept hanging in the corner.
  await saveTab(t);
}

function download(name, text, mime) {
  const blob = new Blob([text], { type: mime + ';charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = name;
  document.body.append(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 4000);
}

/**
 * The export formats.
 *
 * MD and TXT are the file as it is (TXT without markup), they are shown in
 * full and there is nothing to decide there. HTML and PDF are assembled anew,
 * and only for them do the palette, font and size make sense: that is not the
 * styling of the note but the styling of a file that will leave the machine.
 *
 * Each format has its own icon colour. All the icons in the selected segment
 * used to turn the same shade of blue, and four formats read as one toggle; now
 * it is visible which is which.
 */
const EXPORT_FORMATS = [
  { id: 'md', label: 'MD', icon: 'file-text', plain: true, color: 'var(--blue)',
    hint: tr('export.hintSource') },
  { id: 'txt', label: 'TXT', icon: 'file-down', plain: true, color: 'var(--green)',
    hint: tr('export.hintPlain') },
  { id: 'html', label: 'HTML', icon: 'file-code', plain: false, color: 'var(--magenta)',
    hint: tr('export.hintSingleFile') },
  { id: 'pdf', label: 'PDF', icon: 'printer', plain: false, color: 'var(--orange)',
    hint: tr('export.hintPrint') },
];

/*
 * The colour of the "Colour" button.
 *
 * The same colour every time would look like part of the interface: a person
 * gets used to a blue button meaning "colour" and stops reading it. So we take a
 * set from the TokyoNight palette and step through it: the colours are different
 * every time but do not clash, and there is no blue here — that one belongs to MD.
 */
const EXPORT_TINTS = ['var(--green)', 'var(--orange)', 'var(--red)',
  'var(--yellow)', 'var(--purple)'];
let exportTintAt = 0;

function nextExportTint() {
  const c = EXPORT_TINTS[exportTintAt % EXPORT_TINTS.length];
  exportTintAt += 1;
  return c;
}

/** Our own font name for showing in the list: in the CSS it is without a space. */
function exportFontLabel(name) {
  return name === 'JetBrainsMono' ? 'JetBrains Mono' : name;
}

/**
 * The export window.
 *
 * A separate window rather than a list in the ring: the formats have parameters,
 * the parameters have a preview, and none of that fits in a menu. Two actions
 * are left in the ring: "Export" opens this window, "Path" — a short menu about
 * the file path.
 *
 * Settings on the left, preview on the right: the hints were dropped, the cards
 * became low, and there was not enough room for the preview in one column — it
 * came out a narrow strip where neither a heading nor a table was visible.
 */
function exportDialog(preset) {
  const t = active();
  if (!t || !t.path) { toast(tr('export.noNote')); return; }
  if (t.mode === 'edit' && t.dirty) { toast(tr('export.saveFirst')); return; }

  let closeModal = () => back.remove();
  const back = modalShell();
  const box = modalBox(tr('export.title'), 860, 620);
  box.classList.add('exp-box');

  // Settings on the left, preview on the right.
  const body = document.createElement('div');
  body.className = 'exp-body';
  const left = document.createElement('div');
  left.className = 'exp-col exp-left';
  const right = document.createElement('div');
  right.className = 'exp-col exp-right';
  body.append(left, right);
  box.append(body);

  const first = EXPORT_FORMATS.find((f) => f.id === preset) || EXPORT_FORMATS[2];
  const state = {
    format: first.id,
    bw: false,
    size: BASE_TEXT_PX,
    font: 'JetBrainsMono',
  };
  const fmtById = (id) => EXPORT_FORMATS.find((f) => f.id === id) || first;
  // The size card: syncAll refers to it, and it is created below.
  let sizeCard = null;

  /**
   * One setting — a card: a title with the value on the right, the control below.
   * There are no hints: there used to be four of them, and each took a row away
   * from the preview while there was nothing to say — the button caption explains
   * everything anyway.
   */
  function addCard(label, valueEl) {
    const row = document.createElement('div');
    row.className = 'set-row';
    const head = document.createElement('div');
    head.className = 'set-head';
    const l = document.createElement('span');
    l.className = 'set-label';
    l.textContent = label;
    head.append(l);
    if (valueEl) head.append(valueEl);
    row.append(head);
    left.append(row);
    row.addControl = (ctl) => { row.append(ctl); return ctl; };
    return row;
  }

  /** A row of toggles: format, palette. */
  function segmented(options, current, onPick) {
    const wrap = document.createElement('div');
    wrap.className = 'exp-seg';
    const btns = options.map((o) => {
      const b = document.createElement('button');
      b.type = 'button';
      b.className = 'exp-segbtn' + (o.cls ? ' ' + o.cls : '');
      b.dataset.id = o.id;
      if (o.color) b.style.setProperty('--seg', o.color);
      if (o.icon) {
        const ic = document.createElement('span');
        ic.className = 'ico';
        ic.innerHTML = ICONS.icon(o.icon);
        b.append(ic);
      }
      const tx = document.createElement('span');
      tx.textContent = o.label;
      b.append(tx);
      b.onclick = () => onPick(o.id);
      wrap.append(b);
      return b;
    });
    const sync = (id) => btns.forEach((b) => b.classList.toggle('on', b.dataset.id === id));
    sync(current);
    wrap.sync = sync;
    return wrap;
  }

  // ---------------------------------------------------------------- format
  const fmtCard = addCard(tr('export.format'));
  const fmtSeg = segmented(EXPORT_FORMATS.map((f) => ({
    id: f.id, label: f.label, icon: f.icon, color: f.color,
  })), state.format, (id) => {
    state.format = id;
    fmtSeg.sync(id);
    syncAll();
  });
  fmtCard.addControl(fmtSeg);

  // --------------------------------------------------------------- palette
  const palCard = addCard(tr('export.palette'));
  const palSeg = segmented([
    { id: 'colour', label: tr('export.colour'), cls: 'tinted', color: nextExportTint() },
    { id: 'bw', label: tr('export.bw'), cls: 'bw' },
  ], state.bw ? 'bw' : 'colour', (id) => {
    state.bw = id === 'bw';
    palSeg.sync(id);
    syncAll();
  });
  palCard.addControl(palSeg);

  // ----------------------------------------------------------- font size
  const sizeOut = document.createElement('span');
  sizeOut.className = 'set-val';
  const sizeIn = document.createElement('input');
  sizeIn.type = 'range';
  sizeIn.min = '11';
  sizeIn.max = '28';
  sizeIn.step = '1';
  sizeIn.value = String(state.size);
  sizeIn.oninput = () => {
    state.size = +sizeIn.value;
    sizeOut.textContent = sizeIn.value + ' px';
    paintRange(sizeIn);
    syncAll();
  };
  sizeCard = addCard(tr('export.fontSize'), sizeOut);
  sizeCard.addControl(sizeIn);

  // ------------------------------------------------------------------ font
  const fontSel = document.createElement('select');
  fontSel.className = 'exp-select';
  fontSel.disabled = true;
  const fontLoading = document.createElement('option');
  fontLoading.textContent = tr('export.loadingFonts');
  fontSel.append(fontLoading);
  fontSel.onchange = () => {
    state.font = fontSel.value || 'JetBrainsMono';
    syncAll();
  };
  const fontCard = addCard(tr('export.font'));
  fontCard.addControl(fontSel);
  const fillFonts = (names) => {
    fontSel.innerHTML = '';
    const list = (names && names.length ? names : ['JetBrainsMono']).slice();
    if (!list.includes('JetBrainsMono')) list.unshift('JetBrainsMono');
    for (const n of list) {
      const o = document.createElement('option');
      o.value = n;
      o.textContent = exportFontLabel(n);
      fontSel.append(o);
    }
    fontSel.value = state.font;
    fontSel.disabled = false;
  };
  // The fonts are read by main from the Windows registry: the renderer cannot enumerate them.
  Promise.resolve(api.fonts()).then(fillFonts, () => fillFonts(null));

  // --------------------------------------------------------------- preview
  const cap = document.createElement('div');
  cap.className = 'exp-cap';
  cap.textContent = tr('export.preview');
  const prev = document.createElement('div');
  prev.className = 'exp-preview';
  const doc = document.createElement('article');
  doc.className = 'content exp-doc';
  prev.append(doc);
  right.append(cap, prev);

  /*
   * A single pass on any change.
   *
   * The preview shows exactly what will go into the file: for MD — the source
   * text, for TXT — the text without markup, for HTML and PDF — the assembled
   * note with the chosen palette, font and size.
   */
  function syncAll() {
    const f = fmtById(state.format);
    fmtSeg.sync(state.format);
    palSeg.sync(state.bw ? 'bw' : 'colour');
    const plain = !!f.plain;
    // MD and TXT have no styling — showing the palette and the font would be a
    // lie, and a person would tune what is not in the file.
    palCard.hidden = plain;
    sizeCard.hidden = plain;
    fontCard.hidden = plain;
    prev.classList.toggle('bw', !plain && state.bw);
    prev.classList.toggle('plain', plain);
    prev.style.setProperty('--exp-mono',
      '"' + String(state.font).replace(/["'\\]/g, '') + '", monospace');
    prev.style.setProperty('--exp-size', state.size + 'px');
    if (plain) {
      let pre = doc.querySelector('.exp-plain');
      if (!pre) { doc.innerHTML = ''; pre = document.createElement('pre'); pre.className = 'exp-plain'; doc.append(pre); }
      pre.textContent = state.format === 'md' ? t.raw : MDV.mdToText(t.raw);
    } else {
      doc.innerHTML = MDV.renderMd(t.raw, t.baseUrl);
    }
    ok.textContent = tr('export.doIt');
  }

  // ---------------------------------------------------------------- buttons
  const row = document.createElement('div');
  row.className = 'modal-row';
  const cancel = document.createElement('button');
  cancel.className = 'dlgbtn';
  cancel.textContent = tr('btn.cancel');
  cancel.onclick = () => closeModal(false);
  const ok = document.createElement('button');
  ok.className = 'dlgbtn dlgbtn-primary';
  ok.onclick = run;
  row.append(cancel, ok);
  box.append(row);

  back.append(box);
  document.body.append(back);
  closeModal = wireModal(back, () => ok);
  sizeOut.textContent = sizeIn.value + ' px';
  paintRange(sizeIn);
  syncAll();

  // Enter in the window — export. In the font list Enter opens the list itself,
  // there is nothing to confirm with it.
  box.addEventListener('keydown', (e) => {
    if (e.key === 'Enter' && e.target.tagName !== 'SELECT') {
      e.preventDefault();
      e.stopPropagation();
      run();
    }
  });

  let busy = false;

  async function run() {
    if (busy) return;
    const tab = active();
    // While the window is open the tab may have been closed with Ctrl+W — then we
    // would export the wrong thing.
    if (!tab || tab.path !== t.path) { closeModal(false); return; }
    if (tab.mode === 'edit' && tab.dirty) { toast(tr('export.saveFirst')); closeModal(false); return; }

    const base = t.name.replace(/\.md$/i, '');
    busy = true;
    ok.disabled = true;
    ok.textContent = tr('export.preparing');
    try {
      if (state.format === 'md') {
        download(t.name, t.raw, 'text/markdown');
        toast(tr('status.saved') + t.name, 'ok');
      } else if (state.format === 'txt') {
        const file = base + '.txt';
        download(file, MDV.mdToText(t.raw), 'text/plain');
        toast(tr('status.saved') + file, 'ok');
      } else {
        const body = MDV.renderMd(t.raw, t.baseUrl);
        const opts = { font: state.font, size: state.size, bw: state.bw };
        const res = state.format === 'html'
          ? await api.exportHtml({ title: t.name, body, opts })
          : await api.exportPdf({ title: t.name, body, opts });
        toast(tr('status.saved') + res.path + ' (' + fmtSize(res.bytes) + ')', 'ok');
        api.reveal(res.path);
      }
      closeModal(false);
    } catch (e) {
      status(tr('export.error') + (e.message || e), 'err');
      busy = false;
      ok.disabled = false;
      syncAll();
    }
  }
}

