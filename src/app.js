function status(msg, kind) {
  clearTimeout(statusTimer);
  el.statusText.textContent = msg;
  el.statusbar.className = 'statusbar' + (kind ? ' ' + kind : '');
  if (kind === 'err') {
    statusTimer = setTimeout(() => { el.statusbar.className = 'statusbar'; }, 6000);
  } else if (kind === 'warn') {
    statusTimer = setTimeout(() => { el.statusbar.className = 'statusbar'; }, 6000);
  }
}

function fmtSize(b) {
  if (b < 1024) return b + tr('unit.b');
  if (b < 1024 * 1024) return (b / 1024).toFixed(1) + tr('unit.kb');
  return (b / 1048576).toFixed(1) + tr('unit.mb');
}

function basname(p) {
  const parts = String(p).split(/[\\/]/);
  return parts[parts.length - 1] || p;
}

function dirOf(p) {
  const s = String(p);
  const i = Math.max(s.lastIndexOf('/'), s.lastIndexOf('\\'));
  return i > 0 ? s.slice(0, i) : '';
}

/**
 * A confirmation dialog without window.confirm (Electron has none).
 *
 * Built on the shared modalShell/modalBox rather than on inline styles as
 * before: otherwise it did not look like the other windows of the application —
 * a different font, different spacing, no close box.
 *
 * opts:
 *   note        — an explanation under the title (what exactly will be lost)
 *   okClass     — 'primary' | 'danger' | '' (an ordinary button)
 *   cancelText  — the text of the second button
 *   closeIsNo   — the close box and Esc mean "No" (the default).
 *                 For "Save changes?" that is NOT the case: the close box should
 *                 simply close the question and return to editing, otherwise it
 *                 would destroy unsaved work with one click.
 *   xButton     — whether to show the close box
 */
function askConfirm(title, okText, opts) {
  // The tests substitute the answer, so that no dialog opens.
  // null from the hook means "closed without an answer" (the close box, or Esc
  // with closeIsNo:false), so !! cannot be used here: it would turn null into
  // false, that is, into "discard the changes".
  if (__confirmHook) return Promise.resolve(__confirmHook(title, okText));
  const o = opts || {};
  const back = modalShell();
  const box = modalBox(null, 430, 0);
  // The box has to be attached to the backdrop: modalShell() creates only the backdrop itself.
  back.append(box);
  let resolve;

  const head = document.createElement('div');
  head.className = 'dlg-head';
  if (o.xButton !== false) {
    const x = document.createElement('button');
    x.className = 'dlg-x';
    x.title = tr('btn.close');
    x.innerHTML = ICONS.icon('x');
    x.onclick = () => done(o.closeIsNo ? false : null);
    head.append(x);
  }
  const msg = document.createElement('div');
  msg.className = 'dlg-msg';
  msg.textContent = title;
  head.append(msg);
  box.append(head);

  if (o.note) {
    const note = document.createElement('div');
    note.className = 'dlg-note';
    note.textContent = o.note;
    box.append(note);
  }

  const row = document.createElement('div');
  row.className = 'dlg-row';
  const mk = (label, cls) => {
    const b = document.createElement('button');
    b.className = 'dlgbtn' + (cls ? ' dlgbtn-' + cls : '');
    b.textContent = label;
    return b;
  };
  const no = mk(o.cancelText || tr('btn.cancel'), '');
  const yes = mk(okText || tr('btn.ok'), o.okClass || '');
  no.onclick = () => done(false);
  yes.onclick = () => done(true);
  row.append(no, yes);
  box.append(row);

  document.body.append(back);

  let closed = false;
  function done(v) {
    if (closed) return;
    closed = true;
    document.removeEventListener('keydown', onKey, true);
    back.remove();
    // null — "closed without answering": the caller must treat this as
    // "do nothing", not as "no".
    resolve(v);
  }
  const onKey = (e) => {
    // See the comment in wireModal: the node may have been removed from outside,
    // and then this listener hooked onto every subsequent Enter and Escape in the application.
    if (!back.isConnected) {
      document.removeEventListener('keydown', onKey, true);
      return;
    }
    if (e.key === 'Escape') { e.stopPropagation(); e.preventDefault(); done(o.closeIsNo ? false : null); }
    else if (e.key === 'Enter') { e.stopPropagation(); e.preventDefault(); done(true); }
  };
  document.addEventListener('keydown', onKey, true);
  wireModal(back, yes);
  return new Promise((r) => { resolve = r; });
}

/**
 * The shared bricks of modal windows: the backdrop, a box with a title, closing
 * on Esc and on a click outside. askConfirm lives separately — it returns a
 * promise and decides for itself what was pressed.
 *
 * back._onCancel is called when closing WITHOUT saving (Esc, a click outside) —
 * the settings use it to roll back the preview.
 */
function modalShell() {
  const back = document.createElement('div');
  back.className = 'modal-back';
  back._onCancel = null;
  return back;
}

function modalBox(title, width, height) {
  const box = document.createElement('div');
  box.className = 'modal-box';
  if (width) box.style.width = width + 'px';
  if (height) box.style.maxHeight = height + 'px';
  if (title) {
    const h = document.createElement('div');
    h.className = 'modal-title';
    h.textContent = title;
    box.append(h);
  }
  return box;
}

/** Closing on Esc and on a click outside. Returns close(cancelled). */
function wireModal(back, focusTarget) {
  const close = (cancelled) => {
    if (cancelled && back._onCancel) back._onCancel();
    back.remove();
    document.removeEventListener('keydown', onKey, true);
  };
  const onKey = (e) => {
    if (e.key !== 'Escape') return;
    // The window may have been closed in some way other than through close(): the
    // node removed from outside. Then our listener stays hanging on document and
    // the next Escape across the whole application "closes" a non-existent
    // window — for the settings that is a rollback of values just confirmed. We
    // check that the node is still in the document, and at the same time remove
    // the listener: it is not needed any more.
    if (!back.isConnected) {
      document.removeEventListener('keydown', onKey, true);
      return;
    }
    e.stopPropagation();
    e.preventDefault();
    close(true);
  };
  back.addEventListener('mousedown', (e) => {
    // Only a click on the backdrop itself: a click inside the box does not close.
    if (e.target === back) close(true);
  });
  document.addEventListener('keydown', onKey, true);
  const f = typeof focusTarget === 'function' ? focusTarget() : focusTarget;
  if (f && f.focus) f.focus();
  return close;
}

