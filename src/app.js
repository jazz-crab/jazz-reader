/** Leave edit mode with an explicit decision: save or discard. */
/*
 * Leave edit mode for reading.
 *
 * A function of its own because save() leaves earlier if there were no changes:
 * it honestly says "No changes" and does not write the file. But leaving edit
 * mode is still needed — otherwise "Save" with no changes left the person in the
 * editor, and the ring did not help: there was nothing to press.
 */
function endEdit(t) {
  if (!t || t.mode !== 'edit') return;
  // We close the ring: it was assembled for the previous mode of the note, and
  // leaving it open would mean showing "Save" in a note that is no longer editing.
  closeRadial();
  t.mode = 'read';
  t.dirty = false;
  t.html = null;
  renderTabs();
  renderActive();
}

async function exitEdit(saveIt) {
  const t = active();
  if (!t || !t.path || t.mode !== 'edit') return;

  // Enabled autosave removes the very reason to press "Save": leaving edit mode
  // writes the file by itself. The question about discarding is then not needed —
  // there is nothing to discard.
  if (!saveIt && t.dirty && currentSettings.autosave) {
    await save();
    // save() deliberately stays in edit mode (Ctrl+S should not throw you into
    // reading), and here we are specifically leaving — we finish it.
    endEdit(t);
    status(tr('status.autosaved') + t.name, 'ok');
    return;
  }

  if (!saveIt && t.dirty) {
    /*
     * The question is asked as "Save changes?", not as "Discard changes?".
     * The second version asked about the action that had already been invoked,
     * and the buttons "Cancel" / "Discard changes" did not match the name of the
     * question. Here the choice is exhaustive: save or throw away, and closing
     * the window returns to editing with nothing lost.
     *
     * null — the close box or Esc: the question is closed, no answer given, we
     * stay in edit mode.
     */
    const answer = await askConfirm(
      tr('discard.title'),
      tr('btn.save'),
      {
        note: tr('discard.inFile') + t.name + tr('discard.tailHasChanges')
            + tr('discard.willBeLost'),
        okClass: 'primary',
        cancelText: tr('btn.discard'),
        closeIsNo: false,
      }
    );
    // null — closed without an answer: we do nothing, we stay in edit mode.
    if (answer === null) return;
    if (answer === true) {
      await save();
      endEdit(t);
      return;
    }
  }

  if (saveIt) {
    await save();
    endEdit(t);
    return;
  }

  // Discard: we return what is actually on the disk.
  t.raw = t._diskRaw;
  t.dirty = false;
  t.mode = 'read';
  t.html = null;
  renderTabs();
  renderActive();
  status(tr('status.editsDiscarded'), 'warn');
}

/* ------------------------------------------------------- undo and redo

 * A history of our own rather than the browser's Ctrl+Z.
 *
 * The built-in undo works on a field whose value nobody touches from outside.
 * Here the value of the field is overwritten when switching tabs and when
 * leaving edit mode, and that is enough for the Chromium history to be reset:
 * Ctrl+Z did nothing, and the person quite rightly considered the button broken.
 */
const UNDO_COALESCE_MS = 700;
const UNDO_MAX = 300;

function undoState(t) {
  if (!t) return null;
  if (!t.undo) t.undo = [];
  if (!t.redo) t.redo = [];
  return t;
}

/**
 * Remember the state before an edit.
 *
 * @param {object} t   the tab
 * @param {string} tag the kind of edit; identical ones in a row are joined into one step
 */
function pushUndo(t, tag) {
  if (!t || t.mode !== 'edit') return;
  const now = Date.now();
  if (t.undoLast === undefined) t.undoLast = el.editor.value;  // страховка
  const merge = t.undoTag === tag && now - t.undoAt < UNDO_COALESCE_MS;
  if (!merge && t.undoLast !== el.editor.value) {
    t.undo.push(t.undoLast);
    if (t.undo.length > UNDO_MAX) t.undo.shift();
  }
  t.redo.length = 0;
  t.undoTag = tag;
  t.undoAt = now;
  t.undoLast = el.editor.value;
}

/** Enter edit mode with a clean history: there is nothing to undo, no edits yet.
 *  The starting point is what is in the field now: the very first step must know
 *  what to go back to. */
function resetUndo(t) {
  if (!t) return;
  t.undo = [];
  t.redo = [];
  t.undoTag = '';
  t.undoAt = 0;
  t.undoPaste = '';
  t.undoLast = el.editor.value;
}

function applyEditorText(text) {
  const t = active();
  if (!t) return;
  const ed = el.editor;
  // The cursor returns to the old place, cut to the length of the new text: otherwise
  // undo would jump to the start of the note and lose the position it undid from.
  const at = Math.min(ed.selectionStart || 0, text.length);
  ed.value = text;
  try { ed.setSelectionRange(at, at); } catch { /* поле могло быть скрыто */ }
  t.raw = text;
  t.undoLast = text;
  t.dirty = text !== t._diskRaw;
  renderTabs();
  updateReadProgress();
}

function undoEdit() {
  const t = undoState(active());
  if (!t || t.mode !== 'edit') return;
  if (!t.undo.length) { status(tr('err.nothingToUndo'), 'warn'); return; }
  t.redo.push(el.editor.value);
  applyEditorText(t.undo.pop());
  t.undoTag = '';                 // следующий набор начнёт новый шаг
  status(tr('status.undone'), 'ok');
}

function redoEdit() {
  const t = undoState(active());
  if (!t || t.mode !== 'edit') return;
  if (!t.redo.length) { status(tr('err.nothingToRedo'), 'warn'); return; }
  t.undo.push(el.editor.value);
  applyEditorText(t.redo.pop());
  t.undoTag = '';
  status(tr('status.redone'), 'ok');
}

/*
 * The kind of edit, for joining steps. "Paste" is one step as a whole, so we
 * remember the pasted piece: while it matches the tail of the text, the next input
 * is a continuation of the same paste. Typing a line back does not need joining:
 * that is simply text input.
 */
el.editor.addEventListener('paste', (e) => {
  const t = undoState(active());
  const cd = e.clipboardData || window.clipboardData;
  const txt = cd && cd.getData ? cd.getData('text') : '';
  if (t && txt) t.undoPaste = txt;
});

el.editor.addEventListener('input', (e) => {
  updateReadProgress();
  const t = active();
  if (!t) return;
  let tag = 'type';
  const it = e.inputType || '';
  if (t.undoPaste) {
    tag = el.editor.value.endsWith(t.undoPaste) ? 'paste' : 'type';
    t.undoPaste = '';
  } else if (it === 'insertLineBreak' || it === 'insertParagraph') {
    tag = 'newline';
  } else if (it.indexOf('delete') === 0) {
    tag = 'delete';
  }
  pushUndo(t, tag);
  // t.raw must stay in step with the field: renderActive redraws the note and
  // assigns t.raw to the field, and a stale t.raw would wipe what was typed.
  t.raw = el.editor.value;
  t.dirty = t.raw !== t._diskRaw;
  renderTabs();
});

