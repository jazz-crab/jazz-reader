function active() { return tabs.get(activeId) || null; }

/**
 * Switching tabs. touch=false means: do not move the position in the visit stack.
 *
 * On a split screen the tab opens in the pane that has focus, and the one that
 * was showing it moves to the neighbour. That way a note always appears where
 * you are looking. The exception is a click on a tab that is already visible in
 * the other pane: then the panes swap, otherwise there would be emptiness next
 * to the tab itself.
 */
function selectTab(id, touch) {
  if (!tabs.has(id)) return;
  const visibleInSecond = secondId !== null && id === secondId;
  if (secondId !== null && (visibleInSecond || paneFocus === 'second')) {
    if (active()) active().scroll = el.content.scrollTop;
    const other = secondTab();
    if (other) other.scroll2 = el.content2.scrollTop;
    secondId = activeId;
    activeId = id;
    // The new tab is now in the left pane — the focus goes with it.
    setPaneFocus('main');
    renderTabs();
    renderActive();
    renderSecond();
    updateNavButtons();
    return;
  }
  if (active()) active().scroll = el.content.scrollTop;
  activeId = id;
  if (touch !== false) {
    const i = visit.indexOf(id);
    if (i >= 0) visit.splice(i, 1);
    visit.push(id);
    visitPos = visit.length - 1;
  }
  // We switched to another tab — the unfinished load of the first is no longer
  // relevant, otherwise the indicator would hang over the finished text.
  // The loadSeq counter must NOT be touched here: openPath() uses it to know
  // that it was overtaken by a newer request, and blankTab() inside openPath()
  // calls selectTab() quite legitimately.
  hideLoading();
  renderTabs();
  renderActive();
  updateNavButtons();
}

/** Alt+Left/Right when the document history is exhausted: a step along the tab stack. */
function cycleTab(dir) {
  if (visit.length < 2) return;
  const ni = visitPos + dir;
  if (ni < 0 || ni >= visit.length) return;
  visitPos = ni;
  selectTab(visit[ni], false);
}

/**
 * Ctrl+Tab / Ctrl+Shift+Tab go by the ORDER of the tabs, not by the visit
 * history. Both combinations used to go to cycleTab(), that is, along the
 * visit stack: back and forth and back again, while you expect a calm
 * "next/previous" step. In a circle: from the last tab we go to the first.
 */
function stepTab(dir) {
  const ids = [...tabs.keys()];
  if (ids.length < 2) return;
  const i = ids.indexOf(activeId);
  if (i === -1) { selectTab(ids[0]); return; }
  const n = (i + dir + ids.length) % ids.length;
  selectTab(ids[n]);
}

