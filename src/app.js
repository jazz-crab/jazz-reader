/**
 * Opening a large note takes a fraction of a second: reading, rendering the
 * Markdown and inserting into the DOM. Without an indicator the window looks
 * simply hung, so we show it BEFORE reading and hide it only after the frame
 * with the content has reached the screen.
 *
 * requestAnimationFrame does not fire in a minimised or hidden window (our own
 * --jazzreader-hidden included), so we wait for a frame but back it up with a
 * timer: otherwise openPath() would hang forever on a hidden window.
 */
function nextPaint() {
  return new Promise((resolve) => {
    let done = false;
    const fin = () => { if (!done) { done = true; resolve(); } };
    requestAnimationFrame(() => setTimeout(fin, 0));
    setTimeout(fin, 60);
  });
}

