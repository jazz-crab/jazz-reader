function newTab() {
  const id = ++seq;
  tabs.set(id, {
    id, path: null, name: tr('tab.new'), raw: '', html: null,
    dirty: false, mode: 'read', baseUrl: '', encoding: '', size: 0,
    // blank: the person explicitly asked for a new blank tab -> show the
    // default placeholder even if a folder is already open.
    blank: true,
    hist: [], hi: -1, scroll: 0,
  });
  selectTab(id);
  return tabs.get(id);
}

async function closeTab(id, opts) {
  const t = tabs.get(id);
  if (!t) return false;
  // The tab of the right pane was closed — the pane has nothing left to show.
  // We check this here, before the question about changes: otherwise "Save"
  // would close the tab and the pane would stay up with someone else's text.
  const wasSecond = secondId === id;
  // silent — a bulk close ("all others", "all to the right"): we do not fill the
  // screen with five identical questions in a row. But unsaved work is not lost:
  // such tabs are simply not closed, and we report how many are left.
  if (t.dirty) {
    if (opts && opts.silent) return false;
    const answer = await askConfirm(
      tr('discard.title'),
      tr('btn.save'),
      {
        note: tr('discard.inFile') + t.name + tr('discard.hasChanges'),
        okClass: 'primary',
        cancelText: tr('discard.withoutSaving'),
        closeIsNo: false,
      }
    );
    // null — the close box: the question is closed, the tab stays in place.
    if (answer === null) return false;
    if (answer === true) {
      await saveTab(t);
      tabs.delete(id);
      if (activeId === id) {
        const rest = [...tabs.keys()];
        activeId = rest.length ? rest[rest.length - 1] : null;
        if (activeId === null) newTab();
        else selectTab(activeId);
      }
      if (wasSecond) { secondId = null; renderSecond(); }
      renderTabs();
      renderActive();
      return true;
    }
  }
  tabs.delete(id);
  if (wasSecond) { secondId = null; renderSecond(); }
  if (activeId === id) {
    const rest = [...tabs.keys()];
    activeId = null;
    if (rest.length) selectTab(rest[rest.length - 1]);
    else { newTab(); }
  } else {
    renderTabs();
  }
  refreshTreeSelection();
  return true;
}

/** Redraw the highlight of the open files in the tree (cheap, no tree rebuild). */
function refreshTreeSelection() {
  const cur = active() ? active().path : null;
  for (const row of el.paneFiles.querySelectorAll('.tree-item')) {
    const full = row.dataset.path || '';
    const isCur = samePath(cur, full);
    const openInSome = isCur || [...tabs.values()].some((x) => samePath(x.path, full));
    row.classList.toggle('is-open', openInSome);
    row.classList.toggle('active', isCur);
    // We keep the hint only while the file is open in an INactive tab
    row.title = openInSome && !isCur ? full + tr('status.openInOtherTab') : full;
  }
}

/** The tab context menu (right click): close / others / right / left / all. */
/** Bulk close: unsaved tabs are skipped, not lost. */
async function closeMany(list, keepId) {
  let closed = 0, skipped = 0;
  for (const k of list) {
    if (k === keepId) continue;
    const t = tabs.get(k);
    if (t && t.dirty) { skipped++; continue; }
    if (await closeTab(k, { silent: true })) closed++;
  }
  if (skipped) {
    status(tr('status.closedAndSkipped') + closed + tr('status.skippedDirty') + skipped
      + tr('status.saveOrDiscardFirst'), 'err');
  } else if (closed) {
    status(tr('status.tabsClosed') + closed, 'ok');
  }
  if (keepId !== undefined && tabs.has(keepId)) selectTab(keepId);
  return closed;
}
function closeOthers(id) {
  return closeMany([...tabs.keys()], id);
}
function closeToRight(id) {
  const ids = [...tabs.keys()];
  const i = ids.indexOf(id);
  if (i < 0) return Promise.resolve(0);
  return closeMany(ids.slice(i + 1), id);
}
function closeToLeft(id) {
  const ids = [...tabs.keys()];
  const i = ids.indexOf(id);
  if (i < 0) return Promise.resolve(0);
  return closeMany(ids.slice(0, i), id);
}
async function closeAll() {
  const ids = [...tabs.keys()];
  for (const k of ids) {
    const t = tabs.get(k);
    if (t && t.dirty) {
      const answer = await askConfirm(
        tr('discard.title'),
        tr('btn.save'),
        {
          note: tr('discard.inFile') + t.name + tr('discard.hasChanges'),
          okClass: 'primary',
          cancelText: tr('discard.withoutSaving'),
          closeIsNo: false,
        }
      );
      if (answer === null) return;
      if (answer === true) await saveTab(t);
    }
  }
  for (const k of ids) await closeTab(k, { silent: true });
  if (!tabs.size) newTab();
}

/**
 * The shared context menu: {label, hint, act, off} and {sep:true}.
 * One code for both the tab and the file in the tree — otherwise the two copies
 * would drift apart.
 */
/*
 * A context menu with submenus.
 *
 * Open menus live in menuChain in order: the root, its submenu, the submenu of
 * the submenu. Instead of this, every menu used to have a _keep flag, and that
 * brought trouble: the View submenu, having opened once, never closed again —
 * because the flag was set for good.
 *
 * The rule is simple now:
 *   • the cursor left all the open menus — close everything;
 *   • the cursor moved onto another submenu item — close the submenu of that
 *     item, if it was open, and open it;
 *   • a click on an item without a submenu — close everything and run the action.
 *
 * A submenu item keeps its submenu in _sub and does not rebuild it while the
 * chain is alive: otherwise a plain mouse movement back and forth would make the
 * submenu flicker.
 *
 * A menu item:
 *   check: true|false — a checkmark, a toggle item in the View submenu
 *   items: [...]      — a submenu, opening to the right on hover
 *   off               — the item is inactive
 */
let menuChain = [];

/*
 * The "corridor" between the button that opened the menu and the menu itself.
 *
 * The menu is called by a click on the button and opens under it. There is
 * empty space between them — and hovering that space meant "the cursor is
 * outside the menu", that is, closing. On the hamburger it looked like this:
 * you pressed, moved down to "File" — and on the way everything closed, so
 * nothing could be chosen.
 *
 * So we remember the rectangle of the source button and, if the cursor is
 * inside it or inside the rectangle drawn between it and the menu, we do NOT
 * close. It is the corridor, not a delay: a delay on leaving has to be paid on
 * every ordinary close, while the corridor costs empty space on the screen and
 * spoils nothing — a click cannot land there anyway.
 */
let menuCorridor = null;

function menuCorridorFor(anchorRect, menuRect) {
  if (!anchorRect || !menuRect) return null;
  const x0 = Math.min(anchorRect.left, menuRect.left);
  const x1 = Math.max(anchorRect.right, menuRect.right);
  const y0 = Math.min(anchorRect.top, menuRect.top);
  const y1 = Math.max(anchorRect.bottom, menuRect.bottom);
  return { x0, y0, x1, y1 };
}

function inCorridor(pt) {
  if (!menuCorridor) return false;
  const c = menuCorridor;
  return pt.clientX >= c.x0 && pt.clientX <= c.x1 && pt.clientY >= c.y0 && pt.clientY <= c.y1;
}

function closeAllMenus() {
  menuCorridor = null;
  for (const link of menuChain) link.menu.remove();
  menuChain = [];
  document.removeEventListener('mousedown', onMenuDown, true);
  document.removeEventListener('keydown', onMenuKey, true);
  document.removeEventListener('mouseover', onMenuHover, true);
  window.removeEventListener('blur', onMenuBlur);
}

/** Take down the submenu open at an item, without touching the rest of the chain. */
function dropSubmenu(parentMenu, item) {
  const link = menuChain.find((l) => l.parent === parentMenu && l.item === item);
  if (!link) return;
  link.menu.remove();
  menuChain = menuChain.filter((l) => l !== link);
}

function showContextMenu(x, y, items, opts) {
  const o = opts || {};
  // A new root menu closes everything that was open. A submenu does not: it
  // itself already owns an open chain and is simply appended to the end.
  if (!o.parent) closeAllMenus();

  const w = o.width || 232;
  const h = o.height || (items.length * 30 + 14);

  const m = document.createElement('div');
  m.className = 'ctxmenu';
  m.style.left = Math.max(4, Math.min(x, window.innerWidth - w - 6)) + 'px';
  m.style.top = Math.max(4, Math.min(y, window.innerHeight - h - 6)) + 'px';

  for (const it of items) {
    if (it.sep) {
      const sep = document.createElement('div');
      sep.className = 'ctxmenu-sep';
      m.append(sep);
      continue;
    }
    const b = document.createElement('button');
    b.className = 'ctxmenu-item' + (it.danger ? ' ctxmenu-danger' : '');
    b.disabled = !!it.off;

    const l = document.createElement('span');
    l.className = 'ctxmenu-label';
    if (it.check !== undefined) {
      const tick = document.createElement('span');
      tick.className = 'ctxmenu-check';
      tick.textContent = it.check ? '✓' : '';
      l.append(tick);
    }
    // The icon to the left of the caption, on one line with it. The context menu
    // used to have no icons at all, and export from the ring menu came out bare.
    if (it.icon) {
      const ic = document.createElement('span');
      ic.className = 'ico';
      ic.innerHTML = ICONS.icon(it.icon);
      l.append(ic);
    }
    l.append(document.createTextNode(it.label));
    const hn = document.createElement('span');
    hn.className = 'ctxmenu-hint';
    hn.textContent = it.hint !== undefined ? it.hint : (it.items ? '\u203a' : '');
    b.append(l, hn);

    if (it.items) {
      b.classList.add('ctxmenu-parent');
      b.onmouseenter = () => {
        // Moving to a neighbouring submenu item: the old submenu is taken down.
        for (const other of menuChain) {
          if (other.parent === m && other.item !== b) dropSubmenu(m, other.item);
        }
        if (b._sub && b._sub.isConnected) return;   // уже открыто, не мигаем
        const r = b.getBoundingClientRect();
        b._sub = showContextMenu(r.right - 4, r.top - 5, it.items, {
          width: o.subWidth || 232, parent: m, parentItem: b,
        });
      };
      // A click on a submenu item runs nothing: it is not an action.
      b.onclick = (e) => e.stopPropagation();
    } else {
      b.onclick = () => { closeAllMenus(); it.act(); };
    }
    b._index = m.querySelectorAll('.ctxmenu-item').length - 1;
    b._items = it.items || null;
    m.append(b);
  }

  document.body.append(m);
  menuChain.push({ menu: m, parent: o.parent || null, item: o.parentItem || null });
  // The first available item is highlighted right away: the menu is opened from
  // the keyboard — a person must see where Enter will land.
  menuMark(m, menuItemsOf(m).findIndex((b) => !b.disabled));
  if (!o.parent) {
    // The corridor is built once, from the geometry of the root menu: a submenu
    // opens from an item INSIDE the menu, and the cursor is already inside.
    menuCorridor = menuCorridorFor(o.anchorRect, m.getBoundingClientRect());
  }

  // The listeners are put on the whole root, not on every call: otherwise copies
  // would hang on the submenus, and closing one would close the wrong thing.
  if (!o.parent) {
    setTimeout(() => {
      if (!menuChain.length) return;
      document.addEventListener('mousedown', onMenuDown, true);
      document.addEventListener('keydown', onMenuKey, true);
      document.addEventListener('mouseover', onMenuHover, true);
      window.addEventListener('blur', onMenuBlur);
    }, 0);
  }
  m.addEventListener('contextmenu', (e) => e.preventDefault());
  return m;
}

function onMenuDown(e) {
  // A click inside a submenu does not close the menu: a submenu is a separate
  // .ctxmenu, and e.target.closest('.ctxmenu') will find it.
  if (!e.target.closest || !e.target.closest('.ctxmenu')) closeAllMenus();
}

/*
 * Keyboard navigation in the menu.
 *
 *   up/down arrows, j/k — by items;
 *   right/left arrows, l/h — by branches: right opens a submenu, left returns
 *     to the parent;
 *   Enter or Space — confirm;
 *   Esc — close the menu, and if there is no menu, close the window.
 *
 * Both are needed: a person on the keyboard should not have to reach for the
 * mouse, and the mouse has no key. Separators are skipped, the list wraps
 * around, and the current item is shown by a border rather than only by a hover
 * highlight.
 */
function menuItemsOf(menu) {
  return [...menu.querySelectorAll('.ctxmenu-item')];
}

function menuMark(menu, index) {
  const items = menuItemsOf(menu);
  items.forEach((b, k) => b.classList.toggle('cur', k === index));
  const link = menuChain.find((l) => l.menu === menu);
  if (link) link.cur = index;
  const b = items[index];
  if (b) b.scrollIntoView({ block: 'nearest' });
}

/** The neighbouring available item, skipping separators and inactive ones. */
function menuStep(menu, from, dir) {
  const items = menuItemsOf(menu);
  if (!items.length) return -1;
  let k = from;
  for (let n = 0; n < items.length; n += 1) {
    k = (k + dir + items.length) % items.length;
    if (!items[k].disabled) return k;
  }
  return from;
}

function menuCurrent(link) {
  const items = menuItemsOf(link.menu);
  if (link.cur != null && items[link.cur] && !items[link.cur].disabled) return link.cur;
  const first = items.findIndex((b) => !b.disabled);
  return first;
}

/** Open the submenu of an item (as on a mouse hover). */
function menuOpenSub(item) {
  if (!item || !item._items) return false;
  item.dispatchEvent(new MouseEvent('mouseenter'));
  return !!item._sub;
}

function onMenuKey(e) {
  if (e.key === 'Escape') { e.stopPropagation(); closeAllMenus(); return; }
  if (!menuChain.length) return;
  // It works only in the root menu: submenus follow their parent.
  const link = menuChain[0];
  const items = menuItemsOf(link.menu);
  const cur = menuCurrent(link);
  const item = items[cur];
  const k = e.key;

  const isDown = k === 'ArrowDown' || k === 'j' || k === 'J';
  const isUp = k === 'ArrowUp' || k === 'k' || k === 'K';
  const isRight = k === 'ArrowRight' || k === 'l' || k === 'L';
  const isLeft = k === 'ArrowLeft' || k === 'h' || k === 'H';
  const isOk = k === 'Enter' || k === ' ' || k === 'Spacebar';

  if (!isDown && !isUp && !isRight && !isLeft && !isOk) return;
  e.preventDefault();
  e.stopPropagation();

  if (isDown || isUp) {
    const next = menuStep(link.menu, cur, isDown ? 1 : -1);
    menuMark(link.menu, next);
    return;
  }
  if (isRight) {
    if (item && menuOpenSub(item)) menuMark(item._sub, menuCurrent(item._sub));
    return;
  }
  if (isLeft) {
    // We close the deepest submenu: left returns one level up.
    if (menuChain.length > 1) {
      const deep = menuChain[menuChain.length - 1];
      const parentLink = menuChain[menuChain.length - 2];
      dropSubmenu(parentLink.menu, deep.item);
      menuMark(parentLink.menu, parentLink.item
        ? menuItemsOf(parentLink.menu).indexOf(parentLink.item) : menuCurrent(parentLink));
    }
    return;
  }
  if (isOk) {
    if (!item) return;
    if (item._items) {
      menuOpenSub(item);
      menuMark(item._sub, menuCurrent(item._sub));
      return;
    }
    if (!item.disabled) item.click();
  }
}

/**
 * The cursor left all the open menus — we close the chain.
 *
 * There used to be no closing on the cursor leaving at all: a menu with a
 * submenu stayed hanging after the mouse had left it (in the icon menu it looked
 * as if it had got stuck). A mouseover listener rather than mousemove: there are
 * fewer events, and what we need is precisely the departures.
 */
function onMenuHover(e) {
  if (!menuChain.length) return;
  for (const link of menuChain) {
    if (link.menu.contains(e.target)) return;
  }
  if (inCorridor(e)) return;
  closeAllMenus();
}

function onMenuBlur() { closeAllMenus(); }

