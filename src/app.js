/*
 * Which pane "has focus" — the one you looked into last.
 *
 * A new tab opens exactly there. This used to work only for the right pane and
 * only on a click on its tab: in every other case a new note took the left pane,
 * even if for the last half minute you had been looking at the right one. That
 * is exactly what was awkward: you wait for the note to appear where you can see
 * it, and it turns up at the other edge of the screen.
 */
let paneFocus = 'main';

/** Mark the pane that has just been entered. */
function setPaneFocus(which) {
  paneFocus = which;
  // The highlight is needed so that it is visible where the next tab will go.
  // We set it unconditionally, and not only on a change of value: the attribute
  // is the state itself, and it must be right from the first paint, not after the
  // first mouse click.
  el.split.dataset.focus = which;
}
el.split.dataset.focus = paneFocus;

